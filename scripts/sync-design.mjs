#!/usr/bin/env node
/* Copies the BetterMate design system and the comparison captures out of the betterMate workspace into this site.
   The output is committed, so a build never needs the workspace. Run again after the design system changes:

     npm run sync                      # reads ../betterMate
     BETTERMATE_DIR=/path npm run sync

   Writes:
     src/content/design/              tokens.json, the written sections, each component's README, components.json, icons.json
     src/styles/tokens.css, bundle.css  the site's copy of the tokens and the class recipes, fonts beside them
     src/lib/bm-bundle.js             the drawing bundle as an ES module, so pages can draw faces at build time
     public/design/                   tokens.css, bundle.css, bundle.js, fonts and logos for the live previews
     public/previews/<Name>.html      each component's preview as a page of its own
     public/compare/                  stock GaggiMate and BetterMate captures, as webp */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const WS = path.resolve(process.env.BETTERMATE_DIR || path.join(ROOT, '..', 'betterMate'));
const DESIGN = path.join(WS, 'bettermate', 'design');
const REF = path.join(DESIGN, 'reference');
const COMP = path.join(REF, 'components');

if (!fs.existsSync(path.join(DESIGN, 'tokens.json'))) {
  console.error(`No design system at ${DESIGN}. Set BETTERMATE_DIR to the betterMate workspace.`);
  process.exit(1);
}

const out = (...p) => path.join(ROOT, ...p);
const mkdir = (dir) => fs.mkdirSync(dir, { recursive: true });
const write = (file, text) => { mkdir(path.dirname(file)); fs.writeFileSync(file, text); };
const copy = (from, to) => { mkdir(path.dirname(to)); fs.copyFileSync(from, to); };
const read = (file) => fs.readFileSync(file, 'utf8');

/* The site calls it BetterMate, never by a version. "Adaptive v2" is a stock profile's name and stays. */
function scrub(text) {
  return text
    .replace(/BetterMate v2/g, 'BetterMate')
    .replace(/ \(v2\)/g, '')
    .replace(/ are new in v2;/g, ' are new;')
    .replace(/Kept so v1 code still resolves it/g, 'Kept so older code still resolves it')
    .replace(/Moved over from v1/g, 'Moved over from the earlier system');
}

/* ---------- tokens ---------- */
const tokens = JSON.parse(scrub(read(path.join(DESIGN, 'tokens.json'))));
tokens.name = 'BetterMate';
write(out('src/content/design/tokens.json'), JSON.stringify(tokens, null, 1) + '\n');

function colorValue(v) {
  const m = /^\{([a-z0-9-]+)\}$/.exec(v);
  return m ? `var(--${m[1]})` : v;
}
function themeBlock(selector, theme) {
  const lines = tokens.color.tokens.map((t) => {
    const v = typeof t.value === 'string' ? t.value : t.value[theme] ?? t.value.light;
    return `  --${t.name}: ${colorValue(v)};`;
  });
  return `${selector} {\n${lines.join('\n')}\n}\n`;
}
const FAMILIES = ['spacing', 'radius', 'size', 'ring', 'border', 'layer', 'duration', 'easing', 'frame', 'shadow'];
const scalar = FAMILIES.flatMap((f) => (tokens[f]?.tokens || []).map((t) => `  --${t.name}: ${t.value};`));
const fontFaces = tokens.type.fonts
  .map((f) => `@font-face {\n  font-family: '${f.family}';\n  src: url('./fonts/${path.basename(f.file)}') format('woff2');\n  font-weight: ${f.weight};\n  font-style: ${f.style || 'normal'};\n  font-display: swap;\n}\n`)
  .join('');
const tokensCss =
  `/* Generated by scripts/sync-design.mjs from the BetterMate tokens.json. Do not edit. */\n` +
  fontFaces +
  themeBlock(":root,\n[data-theme='light']", 'light') +
  `@media (prefers-color-scheme: dark) {\n${themeBlock(':root:not([data-theme])', 'dark').replace(/^/gm, '  ').trimEnd()}\n}\n` +
  themeBlock("[data-theme='dark']", 'dark') +
  themeBlock("[data-theme='amoled']", 'amoled') +
  `:root {\n  --font-sans: ${tokens.type.families.sans};\n  --font-mono: ${tokens.type.families.mono};\n${scalar.join('\n')}\n}\n`;

const bundleCss = scrub(read(path.join(COMP, 'bundle.css')));
const bundleJs = scrub(read(path.join(COMP, 'bundle.js')));
const fonts = tokens.type.fonts.map((f) => path.join(DESIGN, 'fonts', path.basename(f.file)));

for (const dir of [out('src/styles'), out('public/design')]) {
  write(path.join(dir, 'tokens.css'), tokensCss);
  write(path.join(dir, 'bundle.css'), bundleCss);
  for (const f of fonts) copy(f, path.join(dir, 'fonts', path.basename(f)));
}
write(out('public/design/bundle.js'), bundleJs);
copy(path.join(DESIGN, 'fonts', 'OFL.txt'), out('public/design/fonts/OFL.txt'));
for (const f of ['bettermate-wordmark.svg', 'bettermate-wordmark-inverse.svg']) copy(path.join(DESIGN, 'logos', f), out('public/design/logos', f));

/* The bundle is one IIFE that assigns window.BetterMate. Hand it a window of its own so it runs on the server too. */
write(
  out('src/lib/bm-bundle.js'),
  `/* Generated by scripts/sync-design.mjs from the BetterMate bundle.js. Do not edit. */\n` +
    `const scope = {};\n(function (window) {\n${bundleJs}\n})(scope);\nexport default scope.BetterMate;\n`,
);

/* ---------- written sections ---------- */
for (const f of fs.readdirSync(REF).filter((f) => f.endsWith('.md') && f !== 'SOURCE.md')) {
  write(out('src/content/design/sections', f), scrub(read(path.join(REF, f))));
}
copy(path.join(DESIGN, 'icons.json'), out('src/content/design/icons.json'));

/* ---------- components and their previews ---------- */
const WORDMARK = {
  /* bm-wm--light shows on light grounds, so it carries the ink wordmark; bm-wm--dark carries the inverse. */
  '/_blob/c3209a6e9d2bf07b471210e8ca99a134': '/design/logos/bettermate-wordmark.svg',
  '/_blob/d52403fcf69417a72f969b7ac7bf0dd3': '/design/logos/bettermate-wordmark-inverse.svg',
};
const PREVIEW_HEAD = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>%TITLE%</title>
<link rel="stylesheet" href="/design/tokens.css">
<link rel="stylesheet" href="/design/bundle.css">
<style>html,body{background:var(--surface-0)}body{overflow-x:auto}
@media (prefers-color-scheme:dark){:root:not([data-theme]) .bm-wm--light{display:none}:root:not([data-theme]) .bm-wm--dark{display:block}}</style>
<script>
/* Follow the theme of the page this preview sits in. */
(function () {
  var html = document.documentElement;
  function sync() {
    try {
      var t = parent.document.documentElement.getAttribute('data-theme');
      if (t) html.setAttribute('data-theme', t); else html.removeAttribute('data-theme');
    } catch (e) {}
  }
  sync();
  try { new MutationObserver(sync).observe(parent.document.documentElement, { attributes: true, attributeFilter: ['data-theme'] }); } catch (e) {}
})();
</script>
<script src="/design/bundle.js"></script>
</head>
<body>
`;

const components = [];
for (const name of fs.readdirSync(COMP).filter((n) => fs.statSync(path.join(COMP, n)).isDirectory()).sort()) {
  const previewFile = path.join(COMP, name, 'preview.html');
  const readmeFile = path.join(COMP, name, 'README.md');
  if (!fs.existsSync(previewFile)) continue;
  let preview = scrub(read(previewFile));
  const card = /<!--\s*@dsCard([^>]*)-->/.exec(preview)?.[1] || '';
  const attr = (k) => {
    const m = new RegExp(`${k}=(?:"([^"]*)"|(\\S+))`).exec(card);
    return m ? m[1] ?? m[2] : undefined;
  };
  for (const [blob, file] of Object.entries(WORDMARK)) preview = preview.split(blob).join(file);
  const body = /<body[^>]*>([\s\S]*)<\/body>/i.exec(preview)?.[1].trim() || '';
  const head = /<head[^>]*>([\s\S]*?)<\/head>/i.exec(preview)?.[1] || '';
  const styles = [...head.matchAll(/<style[\s\S]*?<\/style>/gi)].map((m) => m[0]).join('\n');
  const title = /<title>([^<]*)<\/title>/i.exec(preview)?.[1] || name;
  write(out('public/previews', `${name}.html`), PREVIEW_HEAD.replace('%TITLE%', title) + (styles ? styles + '\n' : '') + body + '\n</body>\n</html>\n');

  const readme = fs.existsSync(readmeFile) ? scrub(read(readmeFile)) : '';
  if (readme) write(out('src/content/design/components', name, 'README.md'), readme);
  /* The markup shown under a preview: the body without its scripts. */
  const markup = body.replace(/<script[\s\S]*?<\/script>/gi, '').trim();
  write(out('src/content/design/components', name, 'markup.html'), markup + '\n');
  const summary = readme.split('\n').find((l) => l.trim() && !l.startsWith('#'))?.trim() || '';
  components.push({
    name,
    title,
    group: attr('group') || 'Other',
    height: Number(attr('height')) || 320,
    width: Number(attr('width')) || null,
    summary,
  });
}
write(out('src/content/design/components.json'), JSON.stringify(components, null, 1) + '\n');

/* ---------- comparison captures ---------- */
const STOCK_WEB = path.join(WS, 'visual-identity', 'current');
const STOCK_DISPLAY = path.join(WS, 'visual-identity', 'current-display');
const BM_DISPLAY = path.join(WS, 'bettermate', 'docs', 'display', 'v2');
const BM_WEB = path.join(WS, 'bettermate', 'docs', 'webui');
const webShots = fs.readdirSync(STOCK_WEB).filter((f) => f.endsWith('.png')).sort();
const stockWeb = (stamp) => path.join(STOCK_WEB, webShots.find((f) => f.includes(stamp)));

const CAPTURES = [
  ...['standby', 'brew', 'brew-adjust', 'status-brewing', 'status-finished', 'menu', 'steam-heating', 'steam-active', 'water', 'grind', 'profile', 'info'].map((n) => [
    path.join(STOCK_DISPLAY, `${n}.png`), `stock/display/${n}.webp`, 480,
  ]),
  ...[
    ['core/standby', 'standby'], ['core/brew-heating', 'brew'], ['profiles/adjust', 'adjust'], ['shot/pulling', 'shot-pulling'],
    ['shot/complete', 'shot-complete'], ['menu/menu-from-standby', 'menu'], ['modes/steam-heating', 'steam-heating'],
    ['modes/steam-steaming', 'steam-steaming'], ['modes/water', 'water'], ['modes/grind-time', 'grind'],
    ['profiles/profiles-first', 'profiles'], ['menu/info-station', 'info'], ['core/brew-light', 'brew-light'],
    ['core/fault-runaway', 'fault'], ['menu/warnings', 'warnings'], ['core/wifi-setup', 'wifi-setup'],
  ].map(([from, to]) => [path.join(BM_DISPLAY, `${from}.png`), `bettermate/display/${to}.webp`, 480]),
  [stockWeb('9.11.31'), 'stock/web/dashboard-desktop.webp', 1600],
  [stockWeb('9.08.38'), 'stock/web/dashboard-desktop-idle.webp', 1600],
  [stockWeb('9.16.31'), 'stock/web/dashboard-phone.webp', 390],
  [stockWeb('9.16.39'), 'stock/web/navigation-phone.webp', 390],
  ...[
    ['dashboard-light', 'dashboard-desktop', 1440], ['dashboard-dark', 'dashboard-desktop-dark', 1440], ['brew-active', 'brew-active', 1440],
    ['phone-dashboard', 'dashboard-phone', 390], ['phone-navigation', 'navigation-phone', 390], ['profiles', 'profiles', 1440],
    ['history', 'history', 1440], ['settings', 'settings', 1440], ['analyzer-loaded', 'analyzer', 1440], ['setup-wifi', 'setup-wifi', 1440],
  ].map(([from, to, w]) => [path.join(BM_WEB, `${from}.png`), `bettermate/web/${to}.webp`, w]),
];
const sizes = {};
for (const [from, to, width] of CAPTURES) {
  if (!fs.existsSync(from)) { console.warn(`missing capture: ${from}`); continue; }
  const dest = out('public/compare', to);
  mkdir(path.dirname(dest));
  execFileSync('magick', [from, '-resize', `${width}x>`, '-quality', '86', dest]);
  const [w, h] = execFileSync('magick', ['identify', '-format', '%w %h', dest]).toString().split(' ').map(Number);
  sizes[`/compare/${to}`] = { w, h };
}
write(out('src/content/captures.json'), JSON.stringify(sizes, null, 1) + '\n');

console.log(`Synced ${components.length} components, ${Object.keys(sizes).length} captures from ${WS}`);
